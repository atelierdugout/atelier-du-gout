import { neon } from "@neondatabase/serverless";

const sql = neon(process.env.DATABASE_URL);

await sql`
CREATE TABLE IF NOT EXISTS haccp_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    task_type text NOT NULL,
    title text NOT NULL,

    equipment_id bigint,
    hygiene_expert_equipment_id bigint,

    scheduled_date date NOT NULL,
    scheduled_time time,

    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'done', 'skipped')),

    completed_at timestamptz,

    temperature numeric(6,2),
    hygiene_expert_record_id bigint,

    evidence_bucket text,
    evidence_path text,

    note text,

    created_at timestamptz NOT NULL DEFAULT now()
);
`;

await sql`
CREATE INDEX IF NOT EXISTS idx_haccp_tasks_schedule
ON haccp_tasks(scheduled_date, scheduled_time);
`;

await sql`
CREATE INDEX IF NOT EXISTS idx_haccp_tasks_status
ON haccp_tasks(status);
`;

console.log("OK : table haccp_tasks créée.");
