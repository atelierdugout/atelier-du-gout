import { neon } from "@neondatabase/serverless";

const sql = neon(process.env.DATABASE_URL);

await sql`
  CREATE TABLE IF NOT EXISTS site_analytics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    visitor_id text NOT NULL,
    session_id text NOT NULL,
    path text NOT NULL,
    section text NOT NULL DEFAULT 'site',
    source text NOT NULL DEFAULT 'direct',
    referrer text,
    utm_source text,
    utm_medium text,
    utm_campaign text
  )
`;

await sql`CREATE INDEX IF NOT EXISTS site_analytics_created_at_idx ON site_analytics (created_at)`;
await sql`CREATE INDEX IF NOT EXISTS site_analytics_visitor_idx ON site_analytics (visitor_id)`;
await sql`CREATE INDEX IF NOT EXISTS site_analytics_session_idx ON site_analytics (session_id)`;
await sql`CREATE INDEX IF NOT EXISTS site_analytics_source_idx ON site_analytics (source)`;
await sql`CREATE INDEX IF NOT EXISTS site_analytics_section_idx ON site_analytics (section)`;

console.log("OK : site_analytics créée dans Neon.");
