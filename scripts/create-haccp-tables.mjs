import { neon } from "@neondatabase/serverless";

const sql = neon(process.env.DATABASE_URL);

await sql`
CREATE TABLE IF NOT EXISTS haccp_temperature_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_name text NOT NULL,
    temperature numeric(6,2) NOT NULL,
    measured_at timestamptz NOT NULL DEFAULT now(),
    note text,
    corrective_action text,
    created_at timestamptz NOT NULL DEFAULT now()
);
`;

await sql`
CREATE TABLE IF NOT EXISTS haccp_controls (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category text NOT NULL,
    title text NOT NULL,
    status text NOT NULL DEFAULT 'ok',
    note text,
    corrective_action text,
    performed_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);
`;

await sql`
CREATE TABLE IF NOT EXISTS haccp_equipment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    category text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now()
);
`;

await sql`
CREATE TABLE IF NOT EXISTS haccp_cleaning_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area text NOT NULL,
    action text NOT NULL,
    status text NOT NULL DEFAULT 'done',
    note text,
    performed_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now()
);
`;

await sql`
CREATE INDEX IF NOT EXISTS idx_haccp_temperature_date
ON haccp_temperature_logs(measured_at DESC);
`;

await sql`
CREATE INDEX IF NOT EXISTS idx_haccp_controls_date
ON haccp_controls(performed_at DESC);
`;

await sql`
CREATE INDEX IF NOT EXISTS idx_haccp_cleaning_date
ON haccp_cleaning_logs(performed_at DESC);
`;

console.log("OK : tables HACCP créées.");
